// 转录上限：音频按 16 kHz 单声道 Float32 整段放在内存里，1 小时约 230 MB
export const MAX_DURATION_SECONDS = 60 * 60;

export default defineTool({
  id: "speech-to-text",
  category: "media",
  input: v.object({
    file: v.pipe(
      v.file(),
      fileType(mediaTypes),
      v.maxSize(1024 * 1024 * 1024),
      v.description(
        "The audio or video file to transcribe (MP3, M4A, WAV, OGG, FLAC, MP4, MOV, WebM or MKV), up to 1 GB and 60 minutes",
      ),
    ),
    language: v.optional(
      v.pipe(
        v.picklist(["auto", ...whisperLanguages]),
        v.metadata({ languageNames: true }),
        v.description("Spoken language as a BCP 47 code, or auto to detect it from the audio"),
      ),
      "auto",
    ),
  }),
  output: v.object({
    text: v.pipe(v.string(), v.description("The transcript as plain text")),
    subtitles: v.pipe(v.file(), v.description("The transcript as SRT subtitles with timestamps")),
  }),
  examples: [
    {
      input: {},
      files: { file: "speech.mp3" },
      output: {
        text: "Hello, every tool on this website runs in your browser.",
        subtitles: { type: "application/x-subrip", maxSize: 200 },
      },
    },
  ],
  // ONNX Runtime 的 WASM 在跨源隔离下才能多线程；有可用的 WebGPU 时 encoder 在 GPU 上跑，否则全部用 WASM。
  // 音频由 Mediabunny 经 WebCodecs 解码。
  runtime: {
    where: "client",
    worker: true,
    crossOriginIsolated: true,
    requires: ["wasm", "webcodecs"],
  },
  // WebMCP 的输入输出只有 JSON，不能传文件（ADR-0016）
  agent: {
    webmcp: false,
    remote: false,
    description:
      "Transcribe speech in an audio or video file to text and SRT subtitles in the browser with Whisper.",
  },
});
